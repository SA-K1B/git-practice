function sayMyName(name) {
    const name = "Miller";
    console.log("My name is " + name);
}
 function sayMyAge(age) {
    const age = "35";
    console.log("My age is " + age);
 }
function sayMyNameAndAge(name, age) {
    console.log("My name is " + name + " and my age is " + age);
}
